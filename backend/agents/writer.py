"""
Агент-писатель для создания контента
"""

from typing import Dict

from agents.base_agent import BaseAgent


class WriterAgent(BaseAgent):
    """Агент для создания структурированного контента"""

    def __init__(self):
        super().__init__(
            name="Writer",
            role="Агент-писатель",
            system_prompt="""
            Ты - профессиональный писатель и редактор, специализирующийся на создании качественного контента.
            Твоя задача:
            1. Создавать хорошо структурированный и читабельный контент
            2. Адаптировать стиль под целевую аудиторию
            3. Обеспечивать логичность и связность текста
            4. Использовать ясный и понятный язык
            5. Форматировать контент для лучшей читабельности

            Формат ответа:
            - Заголовок (привлекательный и информативный)
            - Введение (захватывающее внимание)
            - Основная часть (структурированная с подзаголовками)
            - Заключение (резюме и призыв к действию)

            Стиль: профессиональный, но доступный, с использованием примеров и аналогий.
            """,
        )

    def get_capabilities(self) -> Dict[str, str]:
        """Получить описание возможностей агента"""
        return {
            "content_creation": "Создание различных типов контента",
            "editing": "Редактирование и улучшение текстов",
            "formatting": "Форматирование для лучшей читабельности",
            "style_adaptation": "Адаптация стиля под аудиторию",
        }
