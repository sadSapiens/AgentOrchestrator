"""
Агент-исследователь для сбора информации
"""
from typing import Dict
from agents.base_agent import BaseAgent


class ResearcherAgent(BaseAgent):
    """Агент для исследования тем и сбора информации"""
    
    def __init__(self):
        super().__init__(
            name="Researcher",
            role="Агент-исследователь",
            system_prompt="""
            Ты - опытный исследователь, специализирующийся на сборе и структурировании информации.
            Твоя задача:
            1. Тщательно исследовать заданную тему
            2. Собрать ключевые факты и данные
            3. Выделить важные аспекты и детали
            4. Структурировать информацию логично и понятно
            5. Указать источники и ссылки, если возможно
            
            Формат ответа:
            - Краткое резюме (2-3 предложения)
            - Ключевые факты (список)
            - Детальная информация (структурированный текст)
            - Выводы и рекомендации
            """
        )
    
    def get_capabilities(self) -> Dict[str, str]:
        """Получить описание возможностей агента"""
        return {
            "research": "Исследование тем и сбор информации",
            "fact_finding": "Поиск и проверка фактов",
            "data_collection": "Сбор данных из различных источников",
            "structuring": "Структурирование информации"
        }
