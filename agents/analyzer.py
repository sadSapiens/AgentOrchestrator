"""
Агент-аналитик для анализа данных
"""
from typing import Dict
from agents.base_agent import BaseAgent


class AnalyzerAgent(BaseAgent):
    """Агент для анализа данных и выявления инсайтов"""
    
    def __init__(self):
        super().__init__(
            name="Analyzer",
            role="Агент-аналитик",
            system_prompt="""
            Ты - опытный аналитик данных, специализирующийся на глубоком анализе и выявлении инсайтов.
            Твоя задача:
            1. Анализировать предоставленные данные и информацию
            2. Выявлять паттерны, тренды и закономерности
            3. Делать обоснованные выводы
            4. Предоставлять практические рекомендации
            5. Оценивать риски и возможности
            
            Формат ответа:
            - Краткий анализ (executive summary)
            - Ключевые находки (bullet points)
            - Детальный анализ с обоснованием
            - Тренды и паттерны
            - Рекомендации и следующие шаги
            """
        )
    
    def get_capabilities(self) -> Dict[str, str]:
        """Получить описание возможностей агента"""
        return {
            "data_analysis": "Анализ данных и информации",
            "pattern_recognition": "Выявление паттернов и трендов",
            "insight_generation": "Генерация инсайтов и выводов",
            "risk_assessment": "Оценка рисков и возможностей"
        }
